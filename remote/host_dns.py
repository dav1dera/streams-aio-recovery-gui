"""Apply an explicitly selected resolver before installing replacement-VM tools.

Only this module's fixed, root-owned systemd-resolved drop-in is managed. The
caller supplies the DNS address; no LAN address or user configuration is guessed.
"""
import argparse
import ipaddress
import json
import os
from pathlib import Path
import re
import stat
import subprocess
import sys
import tempfile


REFUSED = 'HOST_DNS_CONFIGURATION_REFUSED'
FAILED = 'HOST_DNS_CONFIGURATION_FAILED'
ERROR_CODES = frozenset({REFUSED, FAILED})
DROP_IN = Path('/etc/systemd/resolved.conf.d/70-streams-aio-recovery.conf')
MARKER = '# Generated by StreamsAIO Recovery host_dns.py; managed DNS override.\n'
MAX_BYTES = 1024
PUBLIC_HOSTS = ('github.com', 'download.docker.com')


class HostDNSError(ValueError):
    """A closed error code, with no paths, command output or private input."""


def _require(condition):
    if not condition:
        raise HostDNSError(REFUSED)


def validate_server(server):
    """Require one canonical address, never a hostname, URL or scoped literal."""
    try:
        _require(isinstance(server, str) and 0 < len(server) <= 45 and '%' not in server)
        address = ipaddress.ip_address(server)
        _require(str(address) == server and not address.is_unspecified
                 and not address.is_loopback and not address.is_multicast
                 and not address.is_link_local and not address.is_reserved)
        if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped:
            _require(False)
        return server
    except (ValueError, TypeError):
        raise HostDNSError(REFUSED) from None


def configuration(server):
    return (MARKER + '[Resolve]\nDNS=' + validate_server(server) + '\nDomains=~.\n').encode('ascii')


def _directory(path, uid=0, gid=0):
    info = path.lstat()
    _require(stat.S_ISDIR(info.st_mode) and info.st_uid == uid and info.st_gid == gid
             and not info.st_mode & 0o022)
    return info


def _parents(path):
    _require(path.is_absolute() and '..' not in path.parts)
    for parent in reversed(path.parents):
        _directory(parent)


def _account():
    import pwd
    _require(sys.platform == 'linux' and os.getuid() == 0 and os.geteuid() == 0)
    user = os.environ.get('SUDO_USER', '')
    _require(re.fullmatch(r'[a-z_][a-z0-9_-]{0,63}', user) is not None and user != 'root')
    account = pwd.getpwnam(user)
    _require(account.pw_name == user and account.pw_uid == 1000 and account.pw_gid == 1000)
    home = Path(account.pw_dir)
    _require(str(home) == account.pw_dir and home.is_absolute() and home != Path('/'))
    _parents(home)
    _directory(home, 1000, 1000)


def _file_info(info):
    _require(stat.S_ISREG(info.st_mode) and info.st_uid == 0 and info.st_gid == 0
             and info.st_nlink == 1 and stat.S_IMODE(info.st_mode) == 0o644
             and info.st_size <= MAX_BYTES)


def _identity(info):
    return (info.st_dev, info.st_ino, info.st_mode, info.st_uid, info.st_gid,
            info.st_nlink, info.st_size, info.st_mtime_ns)


def _existing(path):
    """Read without following links, and reject all unmanaged existing content."""
    try:
        info = path.lstat()
    except FileNotFoundError:
        return None
    _file_info(info)
    descriptor = os.open(path, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0)
                         | getattr(os, 'O_BINARY', 0))
    with os.fdopen(descriptor, 'rb') as source:
        opened = os.fstat(source.fileno())
        _file_info(opened)
        _require(_identity(info) == _identity(opened))
        raw = source.read(MAX_BYTES + 1)
        _require(_identity(opened) == _identity(os.fstat(source.fileno())))
    _require(len(raw) <= MAX_BYTES)
    try:
        lines = raw.decode('ascii').splitlines()
        _require(len(lines) == 4 and lines[2].startswith('DNS='))
        _require(raw == configuration(lines[2][4:]))
    except (UnicodeError, ValueError):
        raise HostDNSError(REFUSED) from None
    return raw, _identity(info)


def _prepare_directory(path):
    _parents(path.parent)
    try:
        _directory(path.parent)
    except FileNotFoundError:
        path.parent.mkdir(mode=0o755)
        os.chown(path.parent, 0, 0)
        _directory(path.parent)


def _atomic_write(path, raw, previous):
    """Publish a complete 0644 file, without clobbering a new competing file."""
    _parents(path)
    descriptor, name = tempfile.mkstemp(prefix='.streams-aio-dns-', dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(descriptor, 'wb') as target:
            os.fchown(target.fileno(), 0, 0)
            os.fchmod(target.fileno(), 0o644)
            target.write(raw)
            target.flush()
            os.fsync(target.fileno())
        _require(_existing(path) == previous)
        if previous is None:
            # A hard link atomically creates an absent target; unlike replace it
            # cannot overwrite a file that appeared after the ownership check.
            os.link(temporary, path, follow_symlinks=False)
        else:
            os.replace(temporary, path)
    finally:
        try:
            temporary.unlink()
        except FileNotFoundError:
            pass


def _command(arguments, timeout, capture=False):
    result = subprocess.run(arguments, stdin=subprocess.DEVNULL,
                            stdout=subprocess.PIPE if capture else subprocess.DEVNULL,
                            stderr=subprocess.DEVNULL, check=True, timeout=timeout,
                            env={'PATH': '/usr/sbin:/usr/bin:/sbin:/bin', 'LC_ALL': 'C'})
    if capture:
        _require(isinstance(result.stdout, bytes) and len(result.stdout) <= 65536)
        return result.stdout


def _restart():
    _command(['/usr/bin/systemctl', 'restart', 'systemd-resolved.service'], 20)


def _verify(server):
    # Read back the running daemon; public lookups alone might still succeed
    # through the router while the requested global override is inactive.
    for command, expected in (('dns', server), ('domain', '~.')):
        output = _command(['/usr/bin/resolvectl', command], 5, capture=True)
        global_values = [line.partition(b':')[2].strip() for line in output.splitlines()
                         if line.startswith(b'Global:')]
        _require(global_values == [expected.encode('ascii')])
    for host in PUBLIC_HOSTS:
        _command(['/usr/bin/getent', 'ahostsv4', host], 10)


def _rollback(path, original, installed):
    _parents(path)
    current = _existing(path)
    _require(current is not None and current[0] == installed)
    if original is None:
        _require(_existing(path) == current)
        path.unlink()
    else:
        _atomic_write(path, original[0], current)


def run(server):
    """Return a public result; failures expose only one of two fixed codes."""
    try:
        server = validate_server(server)
        _account()
        _prepare_directory(DROP_IN)
        original = _existing(DROP_IN)
        desired = configuration(server)
    except Exception:
        raise HostDNSError(REFUSED) from None
    if original is not None and original[0] == desired:
        try:
            _verify(server)
        except Exception:
            raise HostDNSError(FAILED) from None
        return {'schema': 1, 'status': 'PASS', 'server': server, 'action': 'UNCHANGED'}
    changed = False
    try:
        _atomic_write(DROP_IN, desired, original)
        changed = True
        _restart()
        _verify(server)
    except BaseException:
        if changed:
            try:
                _rollback(DROP_IN, original, desired)
            except Exception:
                pass
            finally:
                try:
                    _restart()
                except Exception:
                    pass
        raise HostDNSError(FAILED) from None
    return {'schema': 1, 'status': 'PASS', 'server': server, 'action': 'CHANGED'}


class _Parser(argparse.ArgumentParser):
    def error(self, message):
        raise HostDNSError(REFUSED)


def main(argv=None):
    try:
        parser = _Parser(description='Configure an explicitly selected replacement-host DNS resolver.')
        parser.add_argument('--server', required=True)
        args = parser.parse_args(argv)
        print(json.dumps(run(args.server), sort_keys=True))
        return 0
    except HostDNSError as error:
        code = str(error) if str(error) in ERROR_CODES else FAILED
        print(json.dumps({'error': code}, sort_keys=True))
        print(code, file=sys.stderr)
        return 1
    except Exception:
        print(json.dumps({'error': FAILED}, sort_keys=True))
        print(FAILED, file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
